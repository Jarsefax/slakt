#!/usr/bin/env python3
"""Collect full license texts for modules linked into the Linux release binary."""

import json
import os
from pathlib import Path
import subprocess


def output(*args):
    return subprocess.check_output(args, text=True)


def main():
    # Parse Go's stream of JSON package objects without an additional dependency.
    environment = dict(os.environ, CGO_ENABLED="0", GOOS="linux", GOARCH="amd64")
    raw = subprocess.check_output(
        ["go", "list", "-deps", "-json", "./cmd/slkt"], text=True, env=environment
    )
    decoder = json.JSONDecoder()
    modules = {}
    while raw.strip():
        package, end = decoder.raw_decode(raw.lstrip())
        raw = raw.lstrip()[end:]
        module = package.get("Module", {})
        if module.get("Version"):
            modules[module["Path"]] = module

    parts = [
        "# Third-party notices\n\n"
        "Full license texts for the Go runtime and modules linked into the Linux "
        "AMD64 release. Generated by `python3 scripts/third_party_notices.py`; "
        "regenerate when dependencies change. Test-only modules and modules used "
        "only on other operating systems are not part of this binary.\n"
    ]
    goroot = Path(output("go", "env", "GOROOT").strip())
    # Fedora packages the toolchain license separately from GOROOT.
    go_license = next((p for p in (goroot / "LICENSE", Path("/usr/share/licenses/golang/LICENSE")) if p.is_file()), None)
    if go_license is None:
        raise RuntimeError("Could not locate the Go runtime license")
    parts.append("\n## Go runtime and standard library\n\n```text\n" + go_license.read_text() + "\n```\n")
    for name, module in sorted(modules.items()):
        directory = Path(module["Dir"])
        licenses = sorted(
            p for p in directory.iterdir()
            if p.is_file() and p.name.upper().startswith(("LICENSE", "COPYING", "NOTICE"))
        )
        if not licenses:
            raise RuntimeError(f"Missing license for {name} {module['Version']}")
        parts.append(f"\n## {name} {module['Version']}\n")
        for license_file in licenses:
            parts.append(f"\n{license_file.name}:\n\n```text\n{license_file.read_text()}\n```\n")
    destination = Path("docs/THIRD_PARTY_NOTICES.md")
    destination.write_text("".join(parts))
    print(f"Collected notices for Go and {len(modules)} linked modules in {destination}")


if __name__ == "__main__":
    main()
